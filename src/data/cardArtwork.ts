export function getPokemonDexId(cardName: string): number {
  const lower = cardName.toLowerCase();
  for (const [key, id] of Object.entries(POKEMON_DEX_MAP)) {
    if (lower.includes(key)) {
      return id;
    }
  }
  return 25;
}

export function getOfficialArtworkUrl(dexId: number): string {
  return `https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/other/official-artwork/${dexId}.png`;
}

export function resolveCardArt(cardName: string, pokemonType: string, isTopChase?: boolean): PokemonAsset {
  const cleanName = cardName.trim();
  const dexId = getPokemonDexId(cleanName);
  const artworkUrl = getOfficialArtworkUrl(dexId);
  const pokemonUkDbUrl = getPokemonUkDatabaseUrl(cleanName);

  // 1. Direct match in official scans
  let imageUrl = OFFICIAL_POKEMON_COM_SCANS[cleanName];

  // 2. Fuzzy substring match in official scans
  if (!imageUrl) {
    const lowerClean = cleanName.toLowerCase();
    for (const [key, url] of Object.entries(OFFICIAL_POKEMON_COM_SCANS)) {
      const lowerKey = key.toLowerCase();
      if (lowerClean.includes(lowerKey) || lowerKey.includes(lowerClean.split('(')[0].trim())) {
        imageUrl = url;
        break;
      }
    }
  }

  // 3. Match from Pokemon TCG curated default scans
  if (!imageUrl) {
    const lowerClean = cleanName.toLowerCase();
    for (const [key, url] of Object.entries(POKEMON_TCG_DEFAULT_SCANS)) {
      if (lowerClean.includes(key)) {
        imageUrl = url;
        break;
      }
    }
  }

  // 4. Default guaranteed authentic card scan
  if (!imageUrl) {
    imageUrl = 'https://assets.pokemon.com/assets/cms2/img/cards/web/SWSH45/SWSH45_EN_SV107.png';
  }

  // Attack stats based on type
  const attacksByType: Record<string, { name: string; damage: string; text: string }> = {
    fire: { name: 'G-Max Wildfire', damage: '300', text: 'Discard 2 Energy from this Pokémon.' },
    water: { name: 'Hydro Typhoon', damage: '240', text: 'Does 30 damage to each of your opponent’s Benched Pokémon.' },
    grass: { name: 'Forest Bloom', damage: '210', text: 'Heal 60 damage from this Pokémon.' },
    lightning: { name: 'G-Max Volt Crash', damage: '250', text: 'Flip a coin. If heads, your opponent’s Active Pokémon is now Paralyzed.' },
    psychic: { name: 'Psystrike Eclipse', damage: '270', text: 'This attack’s damage isn’t affected by any effects on the Active Pokémon.' },
    dark: { name: 'Moonlight Calamity', damage: '280', text: 'If your opponent has a Pokémon V in play, this attack does 60 more damage.' },
    dragon: { name: 'Max Burst Draco', damage: '320', text: 'Discard all Basic Fire and Basic Lightning Energy attached to this Pokémon.' },
    colorless: { name: 'Hyper Beam Cannon', damage: '220', text: 'Discard an Energy from your opponent’s Active Pokémon.' },
    steel: { name: 'Metal Core Breaker', damage: '230', text: 'During your next turn, this Pokémon’s attacks do 40 more damage.' },
    fighting: { name: 'Seismic Impact', damage: '260', text: 'This Pokémon also does 30 damage to itself.' },
  };

  const defaultAttack = attacksByType[pokemonType] || attacksByType.colorless;
  const hp = isTopChase ? 330 : 280 + (dexId % 5) * 10;

  return {
    dexId,
    imageUrl,
    artworkUrl,
    pokemonUkDbUrl,
    officialCardSource: 'Pokemon.com UK TCG Database',
    hp,
    attacks: [
      {
        name: defaultAttack.name,
        damage: defaultAttack.damage,
        text: defaultAttack.text,
      },
    ],
  };
}
