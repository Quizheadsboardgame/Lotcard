// Generates direct official Pokemon.com UK TCG card database link
export function getPokemonUkDatabaseUrl(cardName: string): string {
  // Clean up variant strings to search the card on official UK database
  const clean = cardName
    .replace(/\(.*?\)/g, '')
    .replace(/#\d+(\/\d+)?/g, '')
    .replace(/1st Edition/gi, '')
    .replace(/Graded/gi, '')
    .replace(/"/g, '')
    .trim();
  return `https://www.pokemon.com/uk/pokemon-tcg/pokemon-cards/?cardName=${encodeURIComponent(clean)}`;
}

